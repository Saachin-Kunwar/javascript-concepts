// For Loop: for → कति पटक loop चल्ने भन्ने थाहा भएको अवस्थामा उपयोगी। 
for(let i=1; i<=5; i++){
    console.log(i);
}

// while loop: while loop lea condition true vaye samma code execute garcha
// while → कुनै condition pura na huda samma chalauna parne aabasta ma useful

console.log("While Loop");
let j = 1;

while (j <= 5) {
    console.log(j);
    j++;
}

console.log("do..while loop");
// do..while loop lea kamtima yakpatak code execute garcha, tespachi condition check garcha
let k=10;
do{
    console.log(k);
    k++;
}while(k<=6);